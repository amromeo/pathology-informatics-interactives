const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const root=process.env.QA_ROOT || 'http://127.0.0.1:4174/pathology-informatics-interactives/';
 const output='review/topic6';
 const check=async()=>assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),'page has horizontal overflow');
 const select=async(label,value)=>page.getByRole('combobox',{name:label,exact:true}).selectOption(value);
 for(const width of [1365,390]){
  await page.setViewportSize({width,height:900});
  await page.goto(root+'lessons/five-rights-right-test/');
  await page.getByRole('heading',{name:'Designing Repeat-Test Guidance',exact:true}).waitFor();
  await check();
  await page.screenshot({path:output+'/design-'+width+'-opening.png'});
  await page.getByRole('button',{name:'Open debrief',exact:true}).click();
  await page.locator('#lesson-debrief').waitFor();
  await page.getByRole('button',{name:'Run eight encounter checks'}).click();
  assert.match(await page.locator('main').innerText(),/3 \/ 8 checks/);
  for(const [label,value] of [['Person receiving guidance','ordering'],['Information displayed','context'],['Delivery channel','composer'],['Intervention format','inline'],['Time in the workflow','before']]) await select(label,value);
  assert.doesNotMatch(await page.locator('main').innerText(),/3 \/ 8 checks/);
  await page.getByRole('button',{name:'Run eight encounter checks'}).click();
  assert.match(await page.locator('main').innerText(),/8 \/ 8 checks/);
  await select('Encounter to preview','CD-05');
  await select('Intervention format','hard');
  assert.equal(await page.getByRole('button',{name:'Record continued order with reason'}).isDisabled(),true);
  await select('Intervention format','inline');
  await page.getByRole('button',{name:'Record continued order with reason'}).click();
  assert.match(await page.locator('main').innerText(),/An override can represent appropriate care/);
  await page.locator('.cds-preview').scrollIntoViewIfNeeded();
  await check();
  await page.screenshot({path:output+'/design-'+width+'-preview.png'});
  await page.getByRole('button',{name:'Reset lesson interactions'}).click();
  assert.equal(await page.getByRole('combobox',{name:'Person receiving guidance'}).inputValue(),'all');
  await page.goto(root+'lessons/alert-everyone-ignores/');
  await page.getByRole('heading',{name:'Evaluating a Repeat-Test Alert',exact:true}).waitFor();
  await check();
  await page.screenshot({path:output+'/evaluation-'+width+'-opening.png'});
  assert.match(await page.locator('.topic5-dashboard').innerText(),/10 presentations/);
  for(const [label,value] of [['Which orders receive guidance','recent'],['Recipient','ordering'],['Repeat presentations','once'],['Alert format','inline']]) await select(label,value);
  assert.match(await page.locator('.topic5-dashboard').innerText(),/4 presentations · 0 mandatory interruptions · 0 unsafe blocks/);
  await select('Alert format','hard');
  assert.match(await page.locator('.topic5-dashboard').innerText(),/2 unsafe blocks/);
  await select('Alert format','inline');
  await select('Comparison included','no');
  assert.match(await page.locator('main').innerText(),/cannot all be attributed/);
  await select('Comparison included','yes');
  for(const box of await page.getByRole('checkbox').all()) await box.check();
  await page.getByRole('radio',{name:'Investigate the delay, revise the rule and display, and reassess a limited pilot',exact:true}).check();
  assert.match(await page.locator('main').innerText(),/The review plan includes targeting/);
  await page.locator('.cds-trend').scrollIntoViewIfNeeded();
  await check();
  await page.screenshot({path:output+'/evaluation-'+width+'-comparison.png'});
  await page.getByRole('button',{name:'Reset lesson interactions'}).click();
  assert.match(await page.locator('.topic5-dashboard').innerText(),/10 presentations/);
  console.log(width+'px: design, exception, reset, alert targeting, harm, comparison, review plan, overflow passed');
 }
 assert.deepEqual(errors,[]);
 fs.writeFileSync(output+'/browser-result.json',JSON.stringify({root,widths:[1365,390],pageErrors:errors,passed:true},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
